"""File storage for exports and attachments.

* ``local`` (development): files on disk, downloaded through signed, expiring links served by
  the API at ``/files/<key>``.
* ``s3`` (production): any S3-compatible bucket (AWS S3, Cloudflare R2, MinIO), with
  presigned download links.

Keys are generated by the app (e.g. ``exports/<workspace>/<uuid>.zip``), never taken from users.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import time
from functools import lru_cache
from pathlib import Path
from typing import Any, Protocol
from urllib.parse import quote, urlencode

from app.core.config import settings

_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,500}$")


class StorageError(Exception):
    pass


def validate_key(key: str) -> str:
    if not _KEY.match(key) or ".." in key.split("/") or key.endswith("/"):
        raise StorageError("Invalid storage key")
    return key


class Storage(Protocol):
    def put(
        self, key: str, data: bytes, content_type: str = "application/octet-stream"
    ) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def download_url(
        self, key: str, *, expires_in: int = 3600, filename: str | None = None
    ) -> str: ...


def _signature(key: str, expires: int, filename: str) -> str:
    message = f"{key}\n{expires}\n{filename}".encode()
    return hmac.new(settings.secret_key.encode(), message, hashlib.sha256).hexdigest()


def verify_signed_download(key: str, expires: int, filename: str, signature: str) -> bool:
    if expires < int(time.time()):
        return False
    return hmac.compare_digest(_signature(key, expires, filename), signature)


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path_for(self, key: str) -> Path:
        path = (self.root / validate_key(key)).resolve()
        if self.root not in path.parents:
            raise StorageError("Invalid storage key")
        return path

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        path = self.path_for(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def get(self, key: str) -> bytes:
        path = self.path_for(key)
        if not path.is_file():
            raise StorageError("File not found")
        return path.read_bytes()

    def delete(self, key: str) -> None:
        self.path_for(key).unlink(missing_ok=True)

    def download_url(self, key: str, *, expires_in: int = 3600, filename: str | None = None) -> str:
        validate_key(key)
        expires = int(time.time()) + expires_in
        name = filename or key.rsplit("/", 1)[-1]
        query = urlencode(
            {"expires": expires, "filename": name, "sig": _signature(key, expires, name)}
        )
        return f"{settings.api_public_url.rstrip('/')}/files/{quote(key)}?{query}"


class S3Storage:
    def __init__(self, client: Any, bucket: str) -> None:
        self.client = client
        self.bucket = bucket

    @classmethod
    def from_settings(cls) -> S3Storage:
        import boto3

        client = boto3.client(
            "s3",
            endpoint_url=settings.s3_endpoint_url or None,
            region_name=settings.s3_region or None,
            aws_access_key_id=settings.s3_access_key_id or None,
            aws_secret_access_key=settings.s3_secret_access_key or None,
        )
        return cls(client, settings.s3_bucket)

    def put(self, key: str, data: bytes, content_type: str = "application/octet-stream") -> None:
        self.client.put_object(
            Bucket=self.bucket,
            Key=validate_key(key),
            Body=data,
            ContentType=content_type,
            ServerSideEncryption="AES256",
        )

    def get(self, key: str) -> bytes:
        response = self.client.get_object(Bucket=self.bucket, Key=validate_key(key))
        return bytes(response["Body"].read())

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=validate_key(key))

    def download_url(self, key: str, *, expires_in: int = 3600, filename: str | None = None) -> str:
        params: dict[str, str] = {"Bucket": self.bucket, "Key": validate_key(key)}
        if filename:
            params["ResponseContentDisposition"] = f'attachment; filename="{filename}"'
        return str(
            self.client.generate_presigned_url("get_object", Params=params, ExpiresIn=expires_in)
        )


def _local_root() -> Path:
    if settings.storage_local_dir:
        return Path(settings.storage_local_dir)
    return Path(__file__).resolve().parents[2] / "data" / "storage"


@lru_cache
def get_storage() -> Storage:
    if settings.storage_backend == "s3":
        if not settings.s3_bucket:
            raise StorageError("STORAGE_BACKEND=s3 needs S3_BUCKET")
        return S3Storage.from_settings()
    return LocalStorage(_local_root())
